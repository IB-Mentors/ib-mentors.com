# Snapshot the SEO metadata the static mirror ships (titles, descriptions, canonicals, robots, JSON-LD), produced
# there by scripts/fix-og-tags.py, add-canonical-links.py and inject-jsonld.py, into src/lib/seo-data.ts so the
# Next.js pages serve the same tags.   python3 qa/gen-seo.py   (from nextjs/; reads the mirror in the repo root)
import re, json, os, html
os.chdir(os.path.join(os.path.dirname(__file__), ".."))
ROOT = ".."
routes = [r for r in open("qa/framer/routes.txt").read().split("\n") if r]
out = {}
for r in routes:
    f = os.path.join(ROOT, "index.html") if r == "/" else os.path.join(ROOT, r.lstrip("/"), "index.html")
    if not os.path.exists(f): print("missing", r); continue
    h = open(f).read(); hd = h[:h.find("</head>")]
    g = lambda pat: (lambda m: html.unescape(m.group(1)) if m else None)(re.search(pat, hd))
    ld = re.findall(r'<script[^>]*application/ld\+json[^>]*>(.*?)</script>', h, re.S)
    out[r] = {
        "title": g(r"<title>([^<]*)</title>"),
        "description": g(r'<meta name="description" content="([^"]*)"'),
        "canonical": g(r'<link rel="canonical" href="([^"]+)"'),
        "robots": g(r'<meta name="robots" content="([^"]*)"'),
        "jsonld": [json.loads(x) for x in ld],
    }
ts = "// Generated by qa/gen-seo.py from the static mirror's meta tags (repo root). Do not edit by hand.\n"
ts += "export type SeoEntry = { title: string | null; description: string | null; canonical: string | null; robots: string | null; jsonld: unknown[] };\n"
ts += "export const SEO: Record<string, SeoEntry> = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
open("src/lib/seo-data.ts", "w").write(ts)
print(len(out), "routes")
for r in ["/", "/courses/ib-weekly-mentoring", "/blogs/ee-theme-erabi-guide", "/404", "/faq"]:
    e = out.get(r, {}); print(r, e.get("title"), e.get("canonical"), e.get("robots"), [ (j.get("@graph") or [{}])[0].get("@type") for j in e.get("jsonld", [])])
