# Extract the Framer CMS collections (blog posts, courses, mentors) from the SSR HTML in qa/framer/ into typed
# modules under src/content/. Copy is verbatim (including Framer's own typos); rich text keeps its semantic tags.
#   python3 qa/extract-content.py        (run from nextjs/, after qa/fetch-page.sh)
import json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from framerhtml import parse, find, text, clean_rich
os.chdir(os.path.join(os.path.dirname(__file__), ".."))
FR = "qa/framer"

def read(p): return open(f"{FR}/{p}.html").read()
def img(u):
    """framerusercontent URL -> local /framer/<file> (downloaded by qa/gen.py)."""
    m = re.search(r"framerusercontent\.com/(?:images|assets)/([A-Za-z0-9_-]+\.[a-z0-9]+)", u or "")
    return f"/framer/{m.group(1)}" if m else u
def pieces(h, s, e):
    return [text(x) for x in re.findall(r"<(?:p|h[1-6]|li)\b[^>]*>(.*?)</(?:p|h[1-6]|li)>", h[s:e], re.S)]
def first(sp, name, within=None):
    r = find(sp, name, within)
    return r[0] if r else None
def first_img(h, s, e):
    m = re.search(r'<img\b[^>]*>', h[s:e])
    if not m: return None
    tag = m.group(0)
    src = re.search(r'src="([^"]+)"', tag); alt = re.search(r'alt="([^"]*)"', tag)
    return {"src": img(src.group(1)) if src else "", "alt": alt.group(1) if alt else ""}
def ts(name, typ, data, doc):
    return f"// {doc}\n// Generated by qa/extract-content.py from qa/framer/*.html. Edit by hand only if Framer changes.\n{typ}\nexport const {name} = {json.dumps(data, ensure_ascii=False, indent=2)};\n"

sitemap = [l.strip() for l in open(f"{FR}/routes.txt") if l.strip()]
blog_slugs = [r.split("/")[2] for r in sitemap if r.startswith("/blogs/")]
course_slugs = [r.split("/")[2] for r in sitemap if r.startswith("/courses/")]
team_slugs = [r.split("/")[2] for r in sitemap if r.startswith("/teams/")]

# ---------------------------------------------------------------- blog posts
idx = read("blogs"); isp = parse(idx)
cards = {}
for t, a, s, e in find(isp, "Desktop Blog Card "):
    href = re.search(r'href="\./blogs/([^"]+)"', idx[s:s + 400])
    if not href or href.group(1) in cards: continue
    p = pieces(idx, s, e)
    cards[href.group(1)] = {"category": p[0], "title": p[1], "date": p[2], "author": p[3] if len(p) > 3 else None, "image": first_img(idx, s, e)}
# Bylines of the cards Framer only renders after もっと見る on /blogs (not in the SSR HTML), read from the live page.
LIVE_BYLINES = {
    "ib-daigaku-shigan-score-katsuyo": "Y.Y 講師",
    "ib-shiken-chokuzen-taisaku-4weeks": "I.S 講師",
    "ib-hogo-sha-support-5steps": "E.F 講師",
    "ib-mental-management-stress": "N.K 講師",
}
posts = []
for slug in blog_slugs:
    h = read(f"blogs/{slug}"); sp = parse(h)
    ds = first(sp, "Details Section"); w = (ds[2], ds[3])
    title = text(h[first(sp, "Title", w)[2]:first(sp, "Title", w)[3]]) if first(sp, "Title", w) else ""
    date = text(h[first(sp, "Date", w)[2]:first(sp, "Date", w)[3]])
    cat = text(h[first(sp, "Category", w)[2]:first(sp, "Category", w)[3]])
    iw = first(sp, "Image Wrapper", w)
    c = first(sp, "Content", w)
    card = cards.get(slug, {})
    posts.append({
        "slug": slug, "title": title, "date": date, "category": cat,
        "author": card.get("author") or LIVE_BYLINES.get(slug),
        "image": first_img(h, iw[2], iw[3]) if iw else card.get("image"),
        "cardImage": card.get("image"),
        "html": clean_rich(h[c[2]:c[3]]) if c else "",
    })
posts.sort(key=lambda p: p["date"])
open("src/content/blogs.ts", "w").write(ts("BLOG_POSTS",
    "export type BlogPost = {\n  slug: string;\n  title: string;\n  /** As Framer prints it: 2025/02/15 */\n  date: string;\n  category: string;\n  /** Card byline (\"I.H 講師\"); for the cards Framer only renders after もっと見る it is LIVE_BYLINES in qa/extract-content.py. */\n  author: string | null;\n  image: { src: string; alt: string } | null;\n  cardImage: { src: string; alt: string } | null;\n  /** Rich text body (Framer classes stripped): h2/h3/p/ul/ol/li/strong/a/img. */\n  html: string;\n};",
    posts, "Blog posts (Framer CMS collection behind /blogs and /blogs/<slug>), oldest first, as /blogs orders them.").replace("export const BLOG_POSTS =", "export const BLOG_POSTS: BlogPost[] =")
    + "\nexport function getPost(slug: string): BlogPost | undefined {\n  return BLOG_POSTS.find((p) => p.slug === slug);\n}\n")

# ---------------------------------------------------------------- courses
idx = read("courses"); isp = parse(idx)
ccards = {}
for t, a, s, e in find(isp, "Desktop Course Card"):
    href = re.search(r'href="\./courses/([^"]+)"', idx[s:s + 400])
    if not href or href.group(1) in ccards: continue
    p = pieces(idx, s, e)
    ccards[href.group(1)] = {"price": p[0], "priceUnit": p[1], "author": p[2], "title": p[3], "time": p[4], "designation": p[5], "image": first_img(idx, s, e)}
order = list(ccards)
courses = []
for slug in sorted(course_slugs, key=lambda s: order.index(s) if s in order else 99):
    h = read(f"courses/{slug}"); sp = parse(h)
    hs = first(sp, "Hero Section"); hero = pieces(h, hs[2], hs[3])
    ds = first(sp, "Details Section"); w = (ds[2], ds[3])
    blocks = []
    for n in ("Content 01", "Content 02", "Content 03", "Content 04", "Content 05"):
        b = first(sp, n, w)
        blocks.append(clean_rich(h[b[2]:b[3]]) if b else "")
    info = [pieces(h, s, e)[:2] for t, a, s, e in find(sp, "List V1", w)]
    seen = []; [seen.append(x) for x in info if x not in seen]
    c2 = first(sp, "Card 02", w)
    overview = [pieces(h, s, e)[0] for t, a, s, e in find(sp, "List", (c2[2], c2[3]))] if c2 else []
    pt = first(sp, "Price & Title", w); price = pieces(h, pt[2], pt[3]) if pt else []
    dsd = first(sp, "Designation & Short Description", w); mentor = pieces(h, dsd[2], dsd[3]) if dsd else []
    c2p = pieces(h, c2[2], c2[3]) if c2 else []
    courses.append({
        "slug": slug, "title": hero[0] if hero else "", "shortDescription": hero[1] if len(hero) > 1 else "",
        "card": ccards.get(slug),
        "content": blocks,
        "info": seen,
        "detailPrice": price[0] if price else "",
        "overview": list(dict.fromkeys(overview)),
        "overviewDescription": c2p[-1] if c2p else "",
        "mentor": {"designation": mentor[0] if mentor else "", "name": mentor[1] if len(mentor) > 1 else "", "description": mentor[2] if len(mentor) > 2 else ""},
    })
open("src/content/courses.ts", "w").write(ts("COURSES",
    "export type Course = {\n  slug: string;\n  /** Hero title and short description on /courses/<slug> */\n  title: string;\n  shortDescription: string;\n  /** Fields of the Course Card on /courses (and the home page): price is the card's, which differs from detailPrice in Framer. */\n  card: { price: string; priceUnit: string; author: string; title: string; time: string; designation: string; image: { src: string; alt: string } | null } | null;\n  /** Rich text of the detail page's \"Content 01\"..\"Content 05\" layers, in order. */\n  content: string[];\n  /** \"Course Information\" list: [label, value] */\n  info: string[][];\n  detailPrice: string;\n  /** \"Overview\" card list items and the line under it */\n  overview: string[];\n  overviewDescription: string;\n  /** \"Designation & Short Description\" block (mentor) */\n  mentor: { designation: string; name: string; description: string };\n};",
    courses, "Courses (Framer CMS collection behind /courses and /courses/<slug>), in the order /courses lists them.").replace("export const COURSES =", "export const COURSES: Course[] =")
    + "\nexport function getCourse(slug: string): Course | undefined {\n  return COURSES.find((c) => c.slug === slug);\n}\n")

# ---------------------------------------------------------------- mentors
mentors = []
for slug in team_slugs:
    h = read(f"teams/{slug}"); sp = parse(h)
    ds = first(sp, "Details Section"); w = (ds[2], ds[3])
    dsd = first(sp, "Designation & Short Description", w); p = pieces(h, dsd[2], dsd[3])
    socials = []
    for t, a, s, e in find(sp, "Team Social Icon", w):
        m = re.search(r'<a\b[^>]*?(?:href="([^"]*)")?[^>]*data-framer-name="(Team Social Icon V[12])"', h[s:e])
        icon = first_img(h, s, e)
        socials.append({"href": (re.search(r'href="([^"]*)"', h[s:e]) or [None, None])[1], "icon": icon["src"] if icon else None})
    courses_here = list(dict.fromkeys(re.findall(r'href="\.\./courses/([^"]+)"', h[ds[2]:ds[3]])))
    mentors.append({"slug": slug, "designation": p[0], "name": p[1], "description": p[2] if len(p) > 2 else "",
                    "image": first_img(h, ds[2], ds[3]), "socials": socials, "courses": courses_here})
open("src/content/teams.ts", "w").write(ts("MENTORS",
    "export type Mentor = {\n  slug: string;\n  /** University line shown above the name */\n  designation: string;\n  name: string;\n  description: string;\n  image: { src: string; alt: string } | null;\n  /** Social icon links in SSR order (each breakpoint variant appears once per pair: V1 = default, V2 = hover). */\n  socials: { href: string | null; icon: string | null }[];\n  /** Slugs of the course cards shown on the profile */\n  courses: string[];\n};",
    mentors, "Mentors (Framer CMS collection behind /teams and /teams/<slug>).").replace("export const MENTORS =", "export const MENTORS: Mentor[] =")
    + "\nexport function getMentor(slug: string): Mentor | undefined {\n  return MENTORS.find((m) => m.slug === slug);\n}\n")
print(len(posts), "posts;", len(courses), "courses;", len(mentors), "mentors")
for p in posts: print(" ", p["date"], p["slug"], p["author"], p["image"] and p["image"]["src"], len(p["html"]))
